val generateRaspBundleMetadata = tasks.register("generateRaspBundleMetadata") {
    dependsOn(stageRaspBundle)
    val outputFile = stagingDir.map { it.file("bundle-metadata.json") }
    outputs.file(outputFile)

    doLast {
        val root = stagingDir.get().asFile
        fun sha256(file: File): String {
            val digest = MessageDigest.getInstance("SHA-256")
            file.inputStream().use { input ->
                val buffer = ByteArray(8192)
                while (true) {
                    val read = input.read(buffer)
                    if (read < 0) break
                    digest.update(buffer, 0, read)
                }
            }
            return digest.digest().joinToString("") { "%02x".format(it) }
        }

        // Declared catalog counts, derived from the staged manifest so verify_bundle.py can check
        // the manifest it receives against them instead of against hand-written numbers.
        val manifest = groovy.json.JsonSlurper()
            .parse(root.resolve("detections_manifest.json").readBytes()) as Map<*, *>
        val detections = manifest["detections"] as List<*>
        val domainCount = (manifest["evidenceDomains"] as List<*>).size
        val unitCount = detections.sumOf { ((it as Map<*, *>)["evidenceUnits"] as List<*>).size }

        val entries = root.walkTopDown()
            .filter { it.isFile && it.name != "bundle-metadata.json" }
            .sortedBy { it.relativeTo(root).invariantSeparatorsPath }
            .joinToString(",\n") { file ->
                val path = file.relativeTo(root).invariantSeparatorsPath
                "    {\"path\": \"$path\", \"sha256\": \"${sha256(file)}\"}"
            }
        outputFile.get().asFile.writeText(
            """{
  "bundleSchemaVersion": 1,
  "edition": "lab",
  "minSdkVersion": 29,
  "engineVersion": "$tamperProbeEngineVersion",
  "catalogVersion": "$tamperProbeCatalogVersion",
  "catalogSchemaVersion": $tamperProbeCatalogSchemaVersion,
  "evidenceContractVersion": $tamperProbeEvidenceContractVersion,
  "wireSchemaVersion": $tamperProbeWireSchemaVersion,
  "catalogCounts": {"evidenceDomains": $domainCount, "detectors": ${detections.size}, "evidenceUnits": $unitCount},
  "files": [
$entries
  ]
}
"""
        )
    }
}

val prepareRaspBundle = tasks.register<Zip>("prepareRaspBundle") {
