// The adapter checks the catalog it loads at startup against the catalog it was built with.
// Those expectations are derived here from the generated manifest, never written by hand: a
// hand-written count went stale once and silently disabled every injected RASP.
abstract class GenerateRaspCatalogExpectation : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val manifestFile: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val bytes = manifestFile.get().asFile.readBytes()
        val root = groovy.json.JsonSlurper().parse(bytes) as Map<*, *>
        val domainCount = (root["evidenceDomains"] as List<*>).size
        val detections = root["detections"] as List<*>
        val unitCount = detections.sumOf { ((it as Map<*, *>)["evidenceUnits"] as List<*>).size }
        val digest = MessageDigest.getInstance("SHA-256").digest(bytes)
            .joinToString("") { "%02x".format(it) }
        val target = outputDir.get().asFile
            .resolve("io/leemikepop/tamperprobe/lab/rasp/RaspCatalogExpectation.java")
        target.parentFile.mkdirs()
        target.writeText(
            """
            |package io.leemikepop.tamperprobe.lab.rasp;
            |
            |// Generated by :tamperprobe-rasp:generateRaspCatalogExpectation from
            |// tamperprobe/scripts/generated/detections_manifest.json. Do not edit.
            |final class RaspCatalogExpectation {
            |    static final int EVIDENCE_DOMAIN_COUNT = $domainCount;
            |    static final int DETECTOR_COUNT = ${detections.size};
            |    static final int EVIDENCE_UNIT_COUNT = $unitCount;
            |    static final String MANIFEST_SHA256 = "$digest";
            |
            |    private RaspCatalogExpectation() {
            |    }
            |}
            |""".trimMargin()
        )
    }
}

val generateRaspCatalogExpectation = tasks.register<GenerateRaspCatalogExpectation>(
    "generateRaspCatalogExpectation",
) {
    // The generator rewrites the manifest; run it first so the expectation and the staged
    // bundle always come from the same bytes.
    dependsOn(":tamperprobe:generateDetectionsManifest")
    manifestFile.set(rootProject.file("tamperprobe/scripts/generated/detections_manifest.json"))
    outputDir.set(layout.buildDirectory.dir("generated/source/raspCatalogExpectation"))
}

